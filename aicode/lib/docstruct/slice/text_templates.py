# -*- coding: utf-8 -*-
"""
text_templates.py - 各类内容块的"向量化文本模板"
================================================

这些模板决定了切片**最终长什么样**（即送入 embedding 的文本）。

设计原则：
    1. 上下文自包含：每个块都要能独立回答"这是哪里的什么内容"，
       因此注入【所属章节】【页码】【说明】等上下文；
    2. 结构化可读：用【标记】前缀区分字段，便于 LLM 与关键词检索识别；
    3. 模板与算法分离：切片器的逻辑与文案分离，改文案不动代码。
"""

# ---------------------------------------------------------------------------
# 表格整表模板
# ---------------------------------------------------------------------------
# 字段说明：
#   caption      - 表格标题（如"表 2-3 高血压患者随访表"）
#   section_path - 所属章节路径（如"第一部分 居民健康档案管理/五、工作指标"）
#   page_start   - 起始页码
#   page_end     - 结束页码（跨页表格）
#   leading_text - 表格前紧邻的正文段落（说明该表用途）
#   markdown_table - Markdown 表格文本
TABLE_TEMPLATE = """【表格】{caption}
【所属章节】{section_path}
【页码】第 {page_start} 页~第 {page_end} 页
{leading_part}
{markdown_table}"""

# 表格超长截断时追加的提示（保留表头 + 前 N 行）
TRUNCATED_FOOTER = "\n[…共 {total_rows} 行，仅保留前 {kept_rows} 行]"

# ---------------------------------------------------------------------------
# 流程图路径模板
# ---------------------------------------------------------------------------
# path_lines 形如：
#   服务对象 →[预约或直接就诊] 建立居民健康档案
#   建立居民健康档案 →[血压高于正常值] 转诊上级医院
FLOW_TEMPLATE = """【流程图】{title}
【所属章节】{section_path}
流程路径：
{path_lines}"""

# 流程图 + 章节上下文合并模板（P6 检索上下文扩展用）
FLOW_WITH_CONTEXT_TEMPLATE = """【流程图】{title}
【所属章节】{section_path}
流程路径：
{path_lines}

【相关章节说明】
{context_text}"""

# ---------------------------------------------------------------------------
# 复选框模板
# ---------------------------------------------------------------------------
# items_lines 形如：
#   [x] 已建立预防接种证
#   [ ] 需补种
CHECKBOX_TEMPLATE = """【复选框】{section_path}
{items_lines}"""

# ---------------------------------------------------------------------------
# 标题锚点模板
# ---------------------------------------------------------------------------
HEADING_TEMPLATE = "{hashes} {title}\n【章节路径】{section_path}"

# ---------------------------------------------------------------------------
# 图片模板
# ---------------------------------------------------------------------------
# ocr_text_part - 【OCR识别】文本（无则提示）
# llm_part      - 【AI解读】LLM 视觉描述（无则空）
IMAGE_TEMPLATE = """【图片】{section_path}
{ocr_text_part}{llm_part}"""

# 段落统一前缀（注入章节信息，保证上下文自包含）
PARAGRAPH_PREFIX = "【所属章节】{section_path}\n"
